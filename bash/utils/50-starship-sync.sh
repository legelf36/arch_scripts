#!/usr/bin/env bash
#
# 50-starship-sync.sh
#
# Omarchy theme-set hook: keeps Starship's color0-color15 palette in sync
# with the active Omarchy theme's generated Alacritty colors.
#
# Why alacritty.toml and not colors.toml: Omarchy's default starship.toml
# format string references plain ANSI slot names (color0..color15), the
# same convention used by Alacritty/foot/kitty. colors.toml instead uses
# semantic names (accent, muted, red, bright_red, ...) which don't line up
# 1:1 with those slots. alacritty.toml's [colors.normal]/[colors.bright]
# sections are already the resolved ANSI 0-15 values for the theme, so we
# read those.
#
# Install:
#   mkdir -p ~/.config/omarchy/hooks/theme-set.d
#   cp 50-starship-sync.sh ~/.config/omarchy/hooks/theme-set.d/
#   chmod +x ~/.config/omarchy/hooks/theme-set.d/50-starship-sync.sh
#
# Run once by hand to sync immediately:
#   ~/.config/omarchy/hooks/theme-set.d/50-starship-sync.sh
#
# It only ever rewrites the block between the two marker comments below in
# ~/.config/starship.toml. Everything else in that file is left untouched.

set -euo pipefail

STARSHIP_CONFIG="${STARSHIP_CONFIG:-$HOME/.config/starship.toml}"
BEGIN_MARK="# BEGIN OMARCHY PALETTE (auto-generated by 50-starship-sync.sh - do not hand-edit)"
END_MARK="# END OMARCHY PALETTE"

# --- Find the active theme's generated alacritty.toml -----------------------

CANDIDATES=(
  "$HOME/.local/state/omarchy/current/theme/alacritty.toml"
  "$HOME/.config/omarchy/current/theme/alacritty.toml"
  "$HOME/.local/share/omarchy/current/theme/alacritty.toml"
)

ALACRITTY_FILE=""
for c in "${CANDIDATES[@]}"; do
  if [[ -f "$c" ]]; then
    ALACRITTY_FILE="$c"
    break
  fi
done

if [[ -z "$ALACRITTY_FILE" ]]; then
  echo "50-starship-sync: could not find the active theme's alacritty.toml (looked in: ${CANDIDATES[*]})" >&2
  exit 1
fi

# --- Pull a hex value for "key = "..."" out of a given [section] -----------
# Usage: get_color <section> <key> <file>
get_color() {
  local section="$1" key="$2" file="$3"
  awk -v section="$section" -v key="$key" '
    $0 ~ "^\\[" section "\\]" { insec=1; next }
    /^\[/ { insec=0 }
    insec && $0 ~ "^[[:space:]]*"key"[[:space:]]*=" {
      match($0, /"#[0-9A-Fa-f]+"/)
      if (RSTART > 0) {
        val = substr($0, RSTART+1, RLENGTH-2)
        print val
      }
      exit
    }
  ' "$file"
}

# Standard ANSI order: 0 black, 1 red, 2 green, 3 yellow, 4 blue, 5 magenta, 6 cyan, 7 white
ANSI_NAMES=(black red green yellow blue magenta cyan white)

PALETTE_LINES=""
for i in "${!ANSI_NAMES[@]}"; do
  name="${ANSI_NAMES[$i]}"
  val="$(get_color "colors.normal" "$name" "$ALACRITTY_FILE")"
  if [[ -n "$val" ]]; then
    PALETTE_LINES+="color${i} = \"${val}\"
"
  fi
done
for i in "${!ANSI_NAMES[@]}"; do
  name="${ANSI_NAMES[$i]}"
  val="$(get_color "colors.bright" "$name" "$ALACRITTY_FILE")"
  if [[ -n "$val" ]]; then
    PALETTE_LINES+="color$((i+8)) = \"${val}\"
"
  fi
done

if [[ -z "$PALETTE_LINES" ]]; then
  echo "50-starship-sync: no colors.normal/colors.bright entries found in $ALACRITTY_FILE" >&2
  exit 1
fi

# NOTE: "palette = ..." must NOT go inside this block. In TOML a bare
# key=value always belongs to whichever [table] preceded it in the file, and
# this block gets appended/placed after existing tables (e.g. [cmd_duration])
# in a real starship.toml. It's handled separately by ensure_top_level_palette
# below, which places it before any [table] in the file.
NEW_BLOCK="$BEGIN_MARK
[palettes.omarchy]
${PALETTE_LINES}${END_MARK}"

# --- Ensure a top-level `palette = "omarchy"` line exists, before any table -
# TOML rule: bare key=value lines belong to the most recent [table] header
# above them. So this line must be inserted before the FIRST [table] header
# in the whole file, never appended near the bottom.
ensure_top_level_palette() {
  local file="$1"
  local first_table_line
  first_table_line="$(grep -nE '^\[' "$file" | head -1 | cut -d: -f1 || true)"

  if [[ -n "$first_table_line" ]]; then
    # Does a palette= line already exist before the first table header?
    if head -n "$((first_table_line - 1))" "$file" | grep -qE '^[[:space:]]*palette[[:space:]]*='; then
      # Update its value in place, wherever it is (still before first table).
      sed -i "1,$((first_table_line - 1)) s/^[[:space:]]*palette[[:space:]]*=.*/palette = \"omarchy\"/" "$file"
      return
    fi
  fi

  # No top-level palette line yet: prepend one as the very first line.
  local tmp
  tmp="$(mktemp)"
  { printf 'palette = "omarchy"\n'; cat "$file"; } > "$tmp"
  mv "$tmp" "$file"
}

# --- Ensure starship.toml exists, with markers present ----------------------

mkdir -p "$(dirname "$STARSHIP_CONFIG")"

if [[ ! -f "$STARSHIP_CONFIG" ]]; then
  printf 'palette = "omarchy"\n\n%s\n' "$NEW_BLOCK" > "$STARSHIP_CONFIG"
  echo "50-starship-sync: created $STARSHIP_CONFIG with the omarchy palette (color0-color15)."
  exit 0
fi

if ! grep -qF "$BEGIN_MARK" "$STARSHIP_CONFIG"; then
  {
    echo ""
    printf '%s\n' "$NEW_BLOCK"
  } >> "$STARSHIP_CONFIG"
  ensure_top_level_palette "$STARSHIP_CONFIG"
  echo "50-starship-sync: appended the omarchy palette block to $STARSHIP_CONFIG."
  exit 0
fi

TMP_FILE="$(mktemp)"
awk -v begin="$BEGIN_MARK" -v end="$END_MARK" -v newblock="$NEW_BLOCK" '
  $0 == begin { print newblock; skipping=1; next }
  $0 == end   { skipping=0; next }
  skipping    { next }
  { print }
' "$STARSHIP_CONFIG" > "$TMP_FILE"

mv "$TMP_FILE" "$STARSHIP_CONFIG"
ensure_top_level_palette "$STARSHIP_CONFIG"
echo "50-starship-sync: updated color0-color15 in $STARSHIP_CONFIG from $ALACRITTY_FILE."
